std::unordered_map<uint32, uint32> KeyEntry::s_globalPublishIPs;

KeyEntry::KeyEntry() = default;

KeyEntry::~KeyEntry()
{
    if (m_publishingIPs) {
        // Decrease global tracking for each IP
        for (const auto& pip : *m_publishingIPs)
            adjustGlobalPublishTracking(pip.ip, false);
        delete m_publishingIPs;
    }
}

Entry* KeyEntry::copy() const
{
    auto* e = new KeyEntry();
    e->m_address = m_address;
    e->m_tcpPort = m_tcpPort;
    e->m_udpPort = m_udpPort;
    e->m_keyID = m_keyID;
    e->m_sourceID = m_sourceID;
    e->m_size = m_size;
    e->m_lifetime = m_lifetime;
    e->m_source = m_source;
    e->m_fileNames = m_fileNames;
    e->m_tags = m_tags;
    e->m_trustValue = m_trustValue;
    e->m_lastTrustValueCalc = m_lastTrustValueCalc;
    return e;
}

bool KeyEntry::startSearchTermsMatch(const SearchTerm& term)
{
    // Build search cache if needed
    if (m_searchTermCache.isEmpty()) {
        m_searchTermCache = getCommonFileNameLowerCase();
    }
    return searchTermsMatch(term);
}

void KeyEntry::mergeIPsAndFilenames(KeyEntry* from)
{
    // Called on the *new* entry when it replaces a stored one, with the old
    // entry (or nullptr for a first publish) as `from`. The new entry takes over
    // the old one's publisher list, AICH hashes and alternative file names;
    // everything else keeps the refreshed values. MFC Entry.cpp:343-469.
    //
    // Note the direction: this port previously merged the other way round (old
    // absorbing new) and then dropped the new entry on the floor without taking
    // ownership, leaking one KeyEntry per refresh publish and never updating the
    // stored entry's tags, size or lifetime.
    if (m_publishingIPs != nullptr)
        return; // already merged — this instance must be a fresh entry

    // Take the AICH hash this publish reported, if any, out of the way; it is
    // re-added below once we know whether this is a refresh.
    QByteArray newAICHHash;
    if (!m_aichHashes.empty()) {
        newAICHHash = m_aichHashes.front();
        m_aichHashes.clear();
        m_aichHashPopularity.clear();
    }

    bool refresh = false;
    bool fastRefresh = false;

    if (from == nullptr || from->m_publishingIPs == nullptr) {
        // Brand new entry — start the tracking list.
        m_publishingIPs = new std::list<PublishingIP>();
    } else {
        m_aichHashes = from->m_aichHashes;
        m_aichHashPopularity = from->m_aichHashPopularity;

        // Adopt the old publisher list wholesale.
        m_publishingIPs = from->m_publishingIPs;
        from->m_publishingIPs = nullptr;

        for (auto it = m_publishingIPs->begin(); it != m_publishingIPs->end(); ++it) {
            if (it->ip != m_address)
                continue;

            refresh = true;
            PublishingIP cur = *it;
            const time_t now = time(nullptr);
            // Republishing sooner than expected does not count towards filename
            // popularity, so a spammer cannot promote its own name by looping.
            //
            // NB: MFC's condition here is mis-parenthesised —
            // `(tNow < Cur.m_tLastPublish) + (KADEMLIAREPUBLISHTIMES - HR2S(1))`
            // adds a bool to a constant and is therefore always true. We port the
            // evident intent instead.
            if (now < cur.lastPublish + (KADEMLIAREPUBLISHTIMES - HR2S(1)))
                fastRefresh = true;
            cur.lastPublish = now;

            // Track any change in the AICH hash this publisher reports.
            if (!newAICHHash.isEmpty()) {
                if (cur.aichHashIdx == kNoAICHHash) {
                    cur.aichHashIdx = addRemoveAICHHash(newAICHHash, true);
                } else if (cur.aichHashIdx < m_aichHashes.size()
                           && m_aichHashes[cur.aichHashIdx] != newAICHHash) {
                    addRemoveAICHHash(m_aichHashes[cur.aichHashIdx], false);
                    cur.aichHashIdx = addRemoveAICHHash(newAICHHash, true);
                }
            } else if (cur.aichHashIdx != kNoAICHHash
                       && cur.aichHashIdx < m_aichHashes.size()) {
                addRemoveAICHHash(m_aichHashes[cur.aichHashIdx], false);
                cur.aichHashIdx = kNoAICHHash;
            }

            // Move this publisher to the back — the list is oldest-first, which
            // is what the 100-entry cap below relies on.
            m_publishingIPs->erase(it);
            m_publishingIPs->push_back(cur);
            break;
        }

        // Keep the old trust value in case we do not recalculate below.
        m_trustValue = from->m_trustValue;
        m_lastTrustValueCalc = from->m_lastTrustValueCalc;

        // Carry over the alternative file names. This entry has exactly one name
        // (it came from a single publisher); if the old entry already knew it,
        // bump that name's popularity instead of duplicating it.
        FileNameEntry currentName;
        if (!m_fileNames.empty()) {
            currentName = m_fileNames.front();
            m_fileNames.clear();
        }
        bool duplicate = false;
        for (const auto& nameToCopy : from->m_fileNames) {
            FileNameEntry copy = nameToCopy;
            if (kadTagStrToLower(currentName.fileName) == kadTagStrToLower(copy.fileName)) {
                duplicate = true;
                copy.popularityIndex += fastRefresh ? 0u : 1u;
            }
            m_fileNames.push_back(copy);
        }
        if (!duplicate && !currentName.fileName.isEmpty())
            m_fileNames.push_back(currentName);
    }

    if (refresh)
        return; // a refresh changes no publisher counts

    // A publisher we have not seen before for this entry: record it. This is
    // what the whole trust system is built on, and what was missing — nothing
    // ever populated m_publishingIPs, so getTrustValue() was permanently 0 and
    // the trusted-first result ordering never ranked anything.
    PublishingIP add;
    add.lastPublish = time(nullptr);
    add.ip = m_address;
    add.aichHashIdx = newAICHHash.isEmpty() ? kNoAICHHash
                                            : addRemoveAICHHash(newAICHHash, true);
    m_publishingIPs->push_back(add);
    adjustGlobalPublishTracking(add.ip, true);

    // Cap at 100 publishers so calculation/storage stays bounded; drop the
    // oldest, releasing its AICH reference and tracking count.
    if (m_publishingIPs->size() > 100) {
        PublishingIP oldest = m_publishingIPs->front();
        m_publishingIPs->pop_front();
        if (oldest.aichHashIdx != kNoAICHHash && oldest.aichHashIdx < m_aichHashes.size())
            addRemoveAICHHash(m_aichHashes[oldest.aichHashIdx], false);
        adjustGlobalPublishTracking(oldest.ip, false);
    }

    recalculateTrustValue();
}

void KeyEntry::cleanUpTrackedPublishers()
{
    if (!m_publishingIPs)
        return;

    time_t now = time(nullptr);
    constexpr time_t kExpireTime = 60 * 60 * 48; // 48 hours

    auto it = m_publishingIPs->begin();
    while (it != m_publishingIPs->end()) {
        if ((now - it->lastPublish) > kExpireTime) {
            adjustGlobalPublishTracking(it->ip, false);
            it = m_publishingIPs->erase(it);
        } else {
            ++it;
        }
    }
}

float KeyEntry::getTrustValue()
{
    // Recalculate if stale (every 10 minutes)
    uint32 now = static_cast<uint32>(time(nullptr));
    if (m_trustValue == 0.0f || (now - m_lastTrustValueCalc) > 600) {
        recalculateTrustValue();
        m_lastTrustValueCalc = now;
    }
    return m_trustValue;
}

void KeyEntry::writePublishTrackingDataToFile(FileDataIO& data)
{
    if (!m_publishingIPs || m_publishingIPs->empty()) {
        data.writeUInt32(0);
        return;
    }

    data.writeUInt32(static_cast<uint32>(m_publishingIPs->size()));
    for (const auto& pip : *m_publishingIPs) {
        data.writeUInt32(pip.ip.toUint32());
        data.writeUInt32(static_cast<uint32>(pip.lastPublish));
        // AICH hash index (v9+)
        data.writeUInt16(pip.aichHashIdx);
    }

    // Write AICH hashes
    data.writeUInt8(static_cast<uint8>(m_aichHashes.size()));
    for (const auto& hash : m_aichHashes) {
        data.write(hash.constData(), 20);
    }
}

void KeyEntry::readPublishTrackingDataFromFile(FileDataIO& data, bool includesAICH)
{
    uint32 count = data.readUInt32();
    if (count == 0)
        return;

    if (!m_publishingIPs)
        m_publishingIPs = new std::list<PublishingIP>();

    for (uint32 i = 0; i < count; ++i) {
        PublishingIP pip;
        pip.ip = Address::fromHostOrder(data.readUInt32());
        pip.lastPublish = static_cast<time_t>(data.readUInt32());
        if (includesAICH)
            pip.aichHashIdx = data.readUInt16();
        m_publishingIPs->push_back(pip);
        adjustGlobalPublishTracking(pip.ip, true);
    }

    if (includesAICH) {
        uint8 aichCount = data.readUInt8();
        m_aichHashes.resize(aichCount);
        for (uint8 i = 0; i < aichCount; ++i) {
            m_aichHashes[i].resize(20);
            data.read(m_aichHashes[i].data(), 20);
        }
    }
}

void KeyEntry::dirtyDeletePublishData()
{
    // Delete without adjusting global tracking (for mass cleanup)
    delete m_publishingIPs;
    m_publishingIPs = nullptr;
    m_aichHashes.clear();
    m_aichHashPopularity.clear();
}

void KeyEntry::writeTagListWithPublishInfo(FileDataIO& data)
{
    // MFC WriteTagListWithPublishInfo: adds TAG_PUBLISHINFO + optional TAG_KADAICHHASHRESULT
    uint32 nAdditionalTags = 1 + static_cast<uint32>(!m_aichHashes.empty());
    writeTagListInc(data, nAdditionalTags);

    // TAG_PUBLISHINFO (0x33): packed uint32 = (nameCount<<24)|(publishers<<16)|(trust*100)
    uint32 trust = static_cast<uint32>(static_cast<uint16>(getTrustValue() * 100.0f));
    uint32 publishers = m_publishingIPs
        ? static_cast<uint32>(m_publishingIPs->size() % 256) : 0;
    uint32 names = static_cast<uint32>(m_fileNames.size() % 256);
    uint32 tagValue = (names << 24) | (publishers << 16) | trust;
    Tag publishTag(QByteArrayLiteral(TAG_PUBLISHINFO), tagValue);
    io::writeKadTag(data, publishTag);

    // TAG_KADAICHHASHRESULT (0x37): BSOB with popularity + hash pairs
    if (!m_aichHashes.empty()) {
        SafeMemFile aichBuf;
        uint8 count = 0;
        // Count hashes with popularity > 0, limit to ~12 (255 byte BSOB limit)
        for (size_t i = 0; i < m_aichHashes.size(); ++i) {
            if (i < m_aichHashPopularity.size() && m_aichHashPopularity[i] > 0) {
                ++count;
                // 1 + (hashSize * (count+1)) + (1 * (count+1)) > 250 → truncate
                if (1 + (m_aichHashes[i].size() * (count + 1)) + (count + 1) > 250)
                    break;
            }
        }
        aichBuf.writeUInt8(count);
        uint8 written = 0;
        for (size_t i = 0; written < count && i < m_aichHashes.size(); ++i) {
            if (i < m_aichHashPopularity.size() && m_aichHashPopularity[i] > 0) {
                aichBuf.writeUInt8(m_aichHashPopularity[i]);
                aichBuf.write(m_aichHashes[i].constData(), m_aichHashes[i].size());
                ++written;
            }
        }
        QByteArray bsob = aichBuf.buffer().left(static_cast<qsizetype>(aichBuf.length()));
        io::writeKadTagBsob(data, QByteArrayLiteral(TAG_KADAICHHASHRESULT), bsob);
    }
}

void KeyEntry::resetGlobalTrackingMap()
{
    s_globalPublishIPs.clear();
}

