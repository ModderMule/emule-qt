bool KeyEntry::searchTermsMatch(const SearchTerm& term) const
{
    switch (term.type) {
    case SearchTerm::Type::AND:
        return (term.left && searchTermsMatch(*term.left))
               && (term.right && searchTermsMatch(*term.right));

    case SearchTerm::Type::OR:
        return (term.left && searchTermsMatch(*term.left))
               || (term.right && searchTermsMatch(*term.right));

    case SearchTerm::Type::NOT:
        return (term.left && searchTermsMatch(*term.left))
               && !(term.right && searchTermsMatch(*term.right));

    case SearchTerm::Type::String:
        // A string term holds several words ("aaa bbb ccc") and is matched as
        // "aaa AND bbb AND ccc" — ALL must be present. Matching ANY made this
        // node serve massive false positives for multi-word searches.
        // MFC Entry.cpp:242-255.
        if (term.strings.empty())
            return false;
        for (const auto& word : term.strings) {
            if (!m_searchTermCache.contains(word, Qt::CaseInsensitive))
                return false;
        }
        return true;

    case SearchTerm::Type::MetaTag: {
        if (!term.tag.isStr())
            return false;
        const QByteArray key = tagLookupKey(term.tag);
        // TAG_FILEFORMAT is never published separately — it is part of the file
        // name, so match it against the extension. MFC Entry.cpp:258-265.
        if (key == QByteArrayLiteral(TAG_FILEFORMAT)) {
            const QString name = getCommonFileNameLowerCase();
            const qsizetype dot = name.lastIndexOf(QLatin1Char('.'));
            if (dot < 0)
                return false;
            return name.mid(dot + 1).compare(term.tag.strValue(), Qt::CaseInsensitive) == 0;
        }
        // Other string metatags match on full-string case-insensitive equality
        // (MFC EqualKadTagStr, DataIO.cpp:518), not substring — `contains` served
        // false positives (e.g. artist "foo" matching "foobar").
        return getStrTagValue(key).compare(term.tag.strValue(), Qt::CaseInsensitive) == 0;
    }

    case SearchTerm::Type::OpGreaterEqual:
    case SearchTerm::Type::OpLessEqual:
    case SearchTerm::Type::OpGreater:
    case SearchTerm::Type::OpLess:
    case SearchTerm::Type::OpEqual:
    case SearchTerm::Type::OpNotEqual: {
        // A float search tag compares against a stored float tag; MFC has a
        // dedicated float branch (Entry.cpp:296-319). Integer tags take the
        // path below. Forcing a float through the integer path gave wrong results.
        if (term.tag.isFloat()) {
            float entryVal = 0.0f;
            if (!getFloatTagValue(tagLookupKey(term.tag), entryVal))
                return false;
            const float searchVal = term.tag.floatValue();
            switch (term.type) {
            case SearchTerm::Type::OpGreaterEqual: return entryVal >= searchVal;
            case SearchTerm::Type::OpLessEqual:    return entryVal <= searchVal;
            case SearchTerm::Type::OpGreater:      return entryVal > searchVal;
            case SearchTerm::Type::OpLess:         return entryVal < searchVal;
            case SearchTerm::Type::OpEqual:        return entryVal == searchVal;
            case SearchTerm::Type::OpNotEqual:     return entryVal != searchVal;
            default: return false;
            }
        }
        uint64 entryVal = 0;
        if (!getIntTagValue(tagLookupKey(term.tag), entryVal, true))
            return false;
        uint64 searchVal = term.tag.int64Value();
        switch (term.type) {
        case SearchTerm::Type::OpGreaterEqual: return entryVal >= searchVal;
        case SearchTerm::Type::OpLessEqual:    return entryVal <= searchVal;
        case SearchTerm::Type::OpGreater:      return entryVal > searchVal;
        case SearchTerm::Type::OpLess:         return entryVal < searchVal;
        case SearchTerm::Type::OpEqual:        return entryVal == searchVal;
        case SearchTerm::Type::OpNotEqual:     return entryVal != searchVal;
        default: return false;
        }
    }
    }
    return false;
}

void KeyEntry::recalculateTrustValue()
{
    // An indicator of how trustworthy (vs. spammy) this entry is. Each publisher
    // contributes points, but the points for a /24 block are shared out among
    // every entry that block published — so one honest publisher scores the full
    // 10, while a spammer flooding many entries from one network dilutes its own
    // contribution towards zero. Callers treat >= 1.0 as trusted.
    // MFC Entry.cpp:471-505.
    constexpr float kPublishPointsPerSubnet = 10.0f;

    // NB: the staleness stamp is owned by getTrustValue(), which keeps it in
    // time(nullptr) seconds — do not set it here from a tick counter.
    m_trustValue = 0.0f;

    if (!m_publishingIPs)
        return;

    for (const auto& pip : *m_publishingIPs) {
        auto it = s_globalPublishIPs.find(pip.ip.toUint32() & ~0xFFu);
        if (it != s_globalPublishIPs.end() && it->second > 0)
            m_trustValue += kPublishPointsPerSubnet / static_cast<float>(it->second);
    }
}

void KeyEntry::adjustGlobalPublishTracking(const Address& ip, bool increase)
{
    // Keyed by /24 block, not by exact IP — see s_globalPublishIPs.
    const uint32 subnet = ip.toUint32() & ~0xFFu;
    if (increase) {
        ++s_globalPublishIPs[subnet];
    } else {
        auto it = s_globalPublishIPs.find(subnet);
        if (it != s_globalPublishIPs.end()) {
            if (it->second <= 1)
                s_globalPublishIPs.erase(it);
            else
                --it->second;
        }
    }
}

uint16 KeyEntry::addRemoveAICHHash(const QByteArray& hash, bool add)
{
    for (std::size_t i = 0; i < m_aichHashes.size(); ++i) {
        if (m_aichHashes[i] != hash)
            continue;
        if (add) {
            ++m_aichHashPopularity[i];
        } else if (m_aichHashPopularity[i] > 0) {
            --m_aichHashPopularity[i];
        }
        return static_cast<uint16>(i);
    }

    if (!add)
        return kNoAICHHash;

    m_aichHashes.push_back(hash);
    m_aichHashPopularity.push_back(1);
    return static_cast<uint16>(m_aichHashes.size() - 1);
}

