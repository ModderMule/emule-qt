// Tag name constants matching MFC TAG_FILENAME / TAG_FILESIZE etc.
namespace {
const QByteArray kTagFilename = QByteArrayLiteral("\x01");
const QByteArray kTagFilesize = QByteArrayLiteral("\x02");
} // namespace

