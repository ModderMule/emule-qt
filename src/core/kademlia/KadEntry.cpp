Entry::Entry() = default;

Entry* Entry::copy() const
{
    auto* e = new Entry();
    e->m_address = m_address;
    e->m_tcpPort = m_tcpPort;
    e->m_udpPort = m_udpPort;
    e->m_keyID = m_keyID;
    e->m_sourceID = m_sourceID;
    e->m_size = m_size;
    e->m_lifetime = m_lifetime;
    e->m_source = m_source;
    e->m_fileNames = m_fileNames;
    e->m_tags = m_tags;
    return e;
}

namespace {

/// Does @p tag carry the name @p tagName?
///
/// Kad tag names are single bytes on the wire, and io::readKadTag normalizes
/// those to Tag::nameId() with an empty Tag::name(). Callers may hold either
/// shape, so match both — comparing only name() silently failed to find every
/// numeric-ID tag, which is nearly all of them.
[[nodiscard]] bool tagNameMatches(const Tag& tag, const QByteArray& tagName)
{
    if (tagName.size() == 1 && tag.name().isEmpty())
        return tag.nameId() == static_cast<uint8>(tagName[0]);
    return tag.name() == tagName;
}

} // namespace

QByteArray Entry::tagLookupKey(const Tag& tag)
{
    if (tag.name().isEmpty() && tag.nameId() != 0)
        return QByteArray(1, static_cast<char>(tag.nameId()));
    return tag.name();
}

uint64 Entry::getIntTagValue(const QByteArray& tagName, bool includeVirtual) const
{
    uint64 val = 0;
    getIntTagValue(tagName, val, includeVirtual);
    return val;
}

bool Entry::getIntTagValue(const QByteArray& tagName, uint64& outValue, bool includeVirtual) const
{
    // Check virtual tags first
    if (includeVirtual) {
        if (tagName == kTagFilesize) {
            outValue = m_size;
            return true;
        }
    }

    for (const auto& tag : m_tags) {
        if (tagNameMatches(tag, tagName) && tag.isInt64(true)) {
            outValue = tag.int64Value();
            return true;
        }
    }
    return false;
}

bool Entry::getFloatTagValue(const QByteArray& tagName, float& outValue) const
{
    for (const auto& tag : m_tags) {
        if (tagNameMatches(tag, tagName) && tag.isFloat()) {
            outValue = tag.floatValue();
            return true;
        }
    }
    return false;
}

QString Entry::getStrTagValue(const QByteArray& tagName) const
{
    if (tagName == kTagFilename)
        return getCommonFileName();

    for (const auto& tag : m_tags) {
        if (tagNameMatches(tag, tagName) && tag.isStr())
            return tag.strValue();
    }
    return {};
}

void Entry::addTag(Tag tag)
{
    // Some tags are generated by *us* when answering a search and must never be
    // accepted from a publisher — otherwise a spammer can forge its own trust
    // and publisher counts, which writeTagListWithPublishInfo() would then serve
    // alongside our genuine ones. MFC Entry.cpp:188-199.
    const QByteArray key = tagLookupKey(tag);
    if (key == QByteArrayLiteral(TAG_PUBLISHINFO)
        || key == QByteArrayLiteral(TAG_KADAICHHASHRESULT)) {
        logKad(QStringLiteral("Kad: filtered result-only tag received on publish"));
        return;
    }

    m_tags.push_back(std::move(tag));
}

uint32 Entry::getTagCount() const
{
    // Tag count includes virtual tags (filename, filesize)
    uint32 count = static_cast<uint32>(m_tags.size());
    if (!m_fileNames.empty())
        ++count; // filename
    if (m_size > 0)
        ++count; // filesize
    return count;
}

void Entry::writeTagList(FileDataIO& data) const
{
    writeTagListInc(data, 0);
}

QString Entry::getCommonFileName() const
{
    if (m_fileNames.empty())
        return {};

    // Return the filename with highest popularity
    const FileNameEntry* best = nullptr;
    for (const auto& entry : m_fileNames) {
        if (!best || entry.popularityIndex > best->popularityIndex)
            best = &entry;
    }
    return best ? best->fileName : QString();
}

QString Entry::getCommonFileNameLowerCase() const
{
    return kadTagStrToLower(getCommonFileName());
}

void Entry::setFileName(const QString& name)
{
    if (name.isEmpty())
        return;

    // Check if this filename already exists
    QString lower = kadTagStrToLower(name);
    for (auto& entry : m_fileNames) {
        if (kadTagStrToLower(entry.fileName) == lower) {
            ++entry.popularityIndex;
            return;
        }
    }

    // Add new filename
    m_fileNames.push_back({name, 1});
}

