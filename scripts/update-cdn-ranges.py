#!/usr/bin/env python3
"""Regenerates src/core/geo/CdnRanges.inc: the address ranges of CDNs / DDoS shields.

An address in them says nothing about where a site's server is (hoster and tracker flags).
Sources: the prefixes each AS below announces now (RIPEstat), plus the published lists of
Cloudflare and Fastly (not all of it is announced at any time) and CloudFront (AWS's own
AS is mostly hosting). Run now and then; the result is committed.

    python3 scripts/update-cdn-ranges.py
"""

import ipaddress
import json
import pathlib
import sys
import urllib.request

# AS -> operator. Only networks that front other sites: no hosting, no clouds (their
# servers do sit in a country), so no AWS/Google/Azure/OVH/DataPacket/G-Core.
ASNS = {
    13335: "Cloudflare",
    209242: "Cloudflare (Spectrum/WARP)",
    132892: "Cloudflare (APAC)",
    54113: "Fastly",
    20940: "Akamai (edge)",
    16625: "Akamai (edge)",
    57724: "DDoS-Guard",
    59796: "StormWall",
    197068: "Qrator",
    19551: "Imperva Incapsula",
    30148: "Sucuri",
    200325: "BunnyCDN",
}

UA = {"User-Agent": "emuleqt-cdn-ranges/1"}
OUT = pathlib.Path(__file__).resolve().parent.parent / "src/core/geo/CdnRanges.inc"


def fetch(url):
    with urllib.request.urlopen(urllib.request.Request(url, headers=UA), timeout=60) as r:
        return json.load(r)


def fetch_lines(url):
    with urllib.request.urlopen(urllib.request.Request(url, headers=UA), timeout=60) as r:
        return [l.strip() for l in r.read().decode().splitlines() if l.strip()]


def main():
    nets = []
    for asn, name in ASNS.items():
        holder = fetch(f"https://stat.ripe.net/data/as-overview/data.json?resource=AS{asn}")["data"].get("holder", "")
        pfx = [p["prefix"] for p in fetch(f"https://stat.ripe.net/data/announced-prefixes/data.json?resource=AS{asn}")["data"]["prefixes"]]
        print(f"AS{asn:<7} {name:<28} {len(pfx):5} prefixes  ({holder})", file=sys.stderr)
        nets += [ipaddress.ip_network(p, strict=False) for p in pfx]
    aws = fetch("https://ip-ranges.amazonaws.com/ip-ranges.json")
    cf = [p["ip_prefix"] for p in aws["prefixes"] if p["service"] == "CLOUDFRONT"]
    cf += [p["ipv6_prefix"] for p in aws["ipv6_prefixes"] if p["service"] == "CLOUDFRONT"]
    print(f"{'CloudFront':<37} {len(cf):5} prefixes", file=sys.stderr)
    nets += [ipaddress.ip_network(p) for p in cf]
    published = fetch_lines("https://www.cloudflare.com/ips-v4") + fetch_lines("https://www.cloudflare.com/ips-v6")
    fastly = fetch("https://api.fastly.com/public-ip-list")
    published += fastly["addresses"] + fastly["ipv6_addresses"]
    print(f"{'Cloudflare + Fastly published':<37} {len(published):5} prefixes", file=sys.stderr)
    nets += [ipaddress.ip_network(p) for p in published]

    v4 = list(ipaddress.collapse_addresses(n for n in nets if n.version == 4))
    v6 = list(ipaddress.collapse_addresses(n for n in nets if n.version == 6))
    lines = ["// Generated by scripts/update-cdn-ranges.py - do not edit.",
             "// " + ", ".join(sorted(set(ASNS.values()) | {"CloudFront"})),
             f"// {len(v4)} IPv4 + {len(v6)} IPv6 ranges"]
    lines += [f'"{n}",' for n in v4 + v6]
    OUT.write_text("\n".join(lines) + "\n")
    print(f"{OUT}: {len(v4)} v4, {len(v6)} v6", file=sys.stderr)


if __name__ == "__main__":
    main()
